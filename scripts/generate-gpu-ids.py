#!/usr/bin/env python3
"""Generate selection data from downloaded, pinned upstream files (no network).

Usage: generate-gpu-ids.py drm_pciids.h supportedchips.html > gpu-ids
AMD: freebsd/drm-kmod drm_v6.6.25_14/include/drm/drm_pciids.h
NVIDIA: FreeBSD-x86_64/595.104.02/README/supportedchips.html
Only the Current NVIDIA GPUs section is admitted, never legacy appendices.
"""
import hashlib
import re
import sys
from pathlib import Path

radeon, nvidia = [Path(p).read_text() for p in sys.argv[1:]]
assert "#define radeon_PCI_IDS" in radeon
assert "the 595.104.02 driver" in nvidia
current = nvidia.split('<h3>Current NVIDIA GPUs</h3>', 1)[1].split('name="legacy_', 1)[0]
rows = set()
for device, chip in re.findall(r'\{0x1002, 0x([0-9A-Fa-f]{4}),.*?CHIP_(\w+)', radeon):
    rows.add(("1002", device.lower(), "*", "*", "radeonkms", chip.lower()))
for ids in re.findall(r'<tr id="devid([0-9A-Fa-f_]+)">', current):
    parts = ids.lower().split("_")
    assert len(parts) in (1, 3), parts
    device, subvendor, subdevice = parts if len(parts) == 3 else (parts[0], "*", "*")
    rows.add(("10de", device, subvendor, subdevice, "nvidia-drm", "595.104.02"))
assert any(r[1] == "1e04" for r in rows)
assert not any(r[0] == "10de" and r[1] == "0fd5" for r in rows)  # GT 650M
print("# Generated by scripts/generate-gpu-ids.py; do not edit.")
print("# AMD legacy PCI IDs: drm_v6.6.25_14 (MIT source); NVIDIA current: 595.104.02")
for name, data in (("drm_pciids.h", radeon), ("supportedchips.html", nvidia)):
    print(f"# {name} sha256={hashlib.sha256(data.encode()).hexdigest()}")
print("# vendor device subvendor subdevice module family-or-version")
for row in sorted(rows):
    print(" ".join(row))
